def solution(box, n):
    # 접근 : 상자의 가로,세로,높이를 주사위가 넘으면 안된다. 따라서 상자의 가로,세로,높이 에서 주사위 모서리 길이 n을 빼는 횟수의 최대치를 각각 곱하면 주사위의 최대개수를 구할 수 있다.
    
    # 가로, 세로, 높이
    w,l,h = box 
    
    # 가로, 세로, 높이의 각각 n만큼 나눈 몫 구하기
    W = w // n
    L = l // n
    H = h // n
    
    # 주사위의 최대개수 반환
    return W * L * H